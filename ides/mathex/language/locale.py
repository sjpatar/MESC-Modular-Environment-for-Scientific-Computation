def tr(key: str, **kwargs) -> str:
    lang = AppConfig.get_language()
    text = STRINGS.get(lang, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text


def get_doc(func_name: str) -> str:
    lang = AppConfig.get_language()
    key_map = {
        "disp": "disp",
        "দেখুওৱা": "disp",
        "clc": "clc",
        "মচিদিয়া": "clc",
        "plot": "plot",
        "আকা": "plot",
        "pause": "pause",
        "ৰৈযোৱা": "pause",
        "size": "size",
        "আকাৰ": "size",
        "title": "title",
        "শিৰোনামা": "title",
        "xlabel": "xlabel",
        "xলেবেল": "xlabel",
        "ylabel": "ylabel",
        "yলেবেল": "ylabel",
    }

    core_key = key_map.get(func_name, func_name)
    doc = DOCS.get(lang, DOCS["en"]).get(core_key)
    if not doc and lang == "as":
        doc = DOCS["en"].get(core_key)
    return doc
