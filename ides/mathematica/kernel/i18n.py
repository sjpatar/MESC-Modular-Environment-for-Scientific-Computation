def tr(key: str, **kwargs) -> str:
    lang = AppConfig.get_language()
    text = STRINGS.get(lang, STRINGS["en"]).get(key, STRINGS["en"].get(key, key))
    return text.format(**kwargs) if kwargs else text


def step_heading(step_num: int, detail: str | None = None) -> str:
    heading = f"{tr('math_step')} {step_num}"
    if detail:
        return f"{heading} ({detail})"
    return heading
