% অসমীয়া 2D প্লটিং স্মোক টেষ্ট
মচিদিয়া
দেখুওৱা('--- অসমীয়া 2D প্লট টেষ্ট ---')

t = linspace(0, 2*pi, 400);
y1 = sin(t);
y2 = cos(t);

figure(1);
clf;
আকা(t, y1, 'b-');
hold(True);
আকা(t, y2, 'r--');
শিৰোনামা('2D ত্ৰিকোণমিতিক ৰেখাচিত্ৰ');
xলেবেল('কোণ (radian)');
yলেবেল('মান');
সংকেত('sin(t)', 'cos(t)');
গ্ৰিড(True);
hold(False);

figure(2);
clf;
[X, Y] = meshgrid(-2:0.25:2, -2:0.25:2);
U = -Y;
V = X;
quiver(X, Y, U, V);
শিৰোনামা('2D ভেক্টৰ ক্ষেত্ৰ');
xলেবেল('x');
yলেবেল('y');
গ্ৰিড(True);

দেখুওৱা('2D প্লট টেষ্ট সম্পূৰ্ণ হ’ল।')
