দেখুওৱা(area_val)
দেখুওৱা('x -> 0 হলে sin(x)/x ৰ limit:')
দেখুওৱা(limit_val)
দেখুওৱা('sin(x)^2 ৰ [0, 2*pi] ত সমাকল:')
দেখুওৱা(trap_est)

