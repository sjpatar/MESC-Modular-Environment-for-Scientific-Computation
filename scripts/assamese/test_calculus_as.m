limit_val = limit(sin(x)/x, x, 0);

sample_x = linspace(0, 2*pi, 200);
sample_y = sin(sample_x).^2;
trap_est = int(sin(x)^2, x, 0, 2*pi);

দেখুওৱা('অৱকলন:')
দেখুওৱা(df)
