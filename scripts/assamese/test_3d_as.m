% অসমীয়া 3D প্লটিং স্মোক টেষ্ট
মচিদিয়া
দেখুওৱা('--- অসমীয়া 3D প্লট টেষ্ট ---')

t = linspace(0, 6*pi, 250);
x = sin(t);
y = cos(t);
z = t / (2*pi);

figure(3);
clf;
plot3(x, y, z, 'm-');
শিৰোনামা('3D হেলিক্স');
xলেবেল('x');
yলেবেল('y');
zlabel('Turns');
গ্ৰিড(True);

figure(4);
clf;
[X, Y] = meshgrid(-3:0.2:3, -3:0.2:3);
R = sqrt(X.^2 + Y.^2) + 1e-6;
Z = sin(R) ./ R;
surf(X, Y, Z);
শিৰোনামা('3D পৃষ্ঠ');
xলেবেল('x');
yলেবেল('y');
zlabel('z');
colormap('jet');
গ্ৰিড(True);

দেখুওৱা('3D প্লট টেষ্ট সম্পূৰ্ণ হ’ল।')
